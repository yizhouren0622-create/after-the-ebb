def install(rules):
    """Attach text to the rule tables without changing the economy or ending IDs."""
    for e in list(rules.DISCOVERIES.values()) + [e for pool in rules.POOLS.values() for e in pool]:
        e['text'] = TEXT[e['title']]
        for c, result in zip(e['choices'], RESULTS[e['title']]):
            c['narrative'] = result
    rules.TALKS = list(TALKS.items())
    rules.achievements.TALK_TITLES.update(TALKS)
    rules.ENDINGS = {key: (row[0], row[1], ENDINGS[key]) for key, row in rules.ENDINGS.items()}
    import journey_feedback
    journey_feedback.RESPONSES.update(RESULTS)
    journey_feedback.RESPONSES.update({k: [v] for k, v in TALK_RESULTS.items()})


def next_thread(s, rules):
    for row in THREADS:
        if (s['loc'] != row['loc'] or row['id'] in s.setdefault('story_seen', [])
                or s['day'] < row.get('day', 1)
                or s['visits'].get(s['loc'], 0) < row.get('visit', 1)
                or row.get('flag') and row['flag'] not in s['flags']):
            continue
        s['story_seen'].append(row['id'])
        options = []
        for label, effect, cost, result in row['options']:
            c = rules.choice(label, effect, cost, result='经过与变化已记入手记。')
            c['narrative'] = result
            options.append(c)
        return rules.event(row['title'], row['text'], options, '支线 / ' + rules.PLACES[s['loc']][0])
    return None


